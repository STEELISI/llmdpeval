"""List every public class/function in diffprivlib's main modules with inspect.signature.

Usage (from the repo root, in the pinned venv): python corpus/api_index/make_api_index_diffprivlib.py > corpus/api_index/API_INDEX_diffprivlib_0.6.6.txt
"""
import importlib
import inspect

import diffprivlib

MODULES = ["diffprivlib", "diffprivlib.tools", "diffprivlib.mechanisms", "diffprivlib.mechanisms.transforms",
           "diffprivlib.models", "diffprivlib.accountant", "diffprivlib.validation", "diffprivlib.utils"]

print(f"# diffprivlib {diffprivlib.__version__}: public API (generated by make_api_index.py)")
for name in MODULES:
    mod = importlib.import_module(name)
    print(f"\n## {name}")
    for attr in sorted(a for a in dir(mod) if not a.startswith("_")):
        obj = getattr(mod, attr)
        if inspect.ismodule(obj) or not (inspect.isclass(obj) or inspect.isfunction(obj)):
            continue
        try:
            sig = str(inspect.signature(obj))
        except (TypeError, ValueError):
            sig = "(...)"
        kind = "class" if inspect.isclass(obj) else "def"
        where = getattr(obj, "__module__", "")
        print(f"{kind} {name}.{attr}{sig}    [defined in {where}]")
        if inspect.isclass(obj) and where.startswith("diffprivlib"):
            for m, f in sorted(vars(obj).items()):
                if not m.startswith("_") and callable(f):
                    try:
                        print(f"    .{m}{inspect.signature(f)}")
                    except (TypeError, ValueError):
                        pass
